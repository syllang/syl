use super::{SvDesign, SvExpr, SvInstance, SvItem, SvModule, SvParam, SvSelectArm};

/// Owns the output buffer while rendering backend IR.
///
/// Keeping formatting here leaves the IR nodes as value objects.  The printer
/// is the single place that knows indentation, declaration ranges, and the
/// textual spelling of nested expressions.
struct SvPrinter<'a> {
    out: &'a mut String,
}

pub(super) fn text(design: &SvDesign) -> String {
    let mut out = String::new();
    SvPrinter { out: &mut out }.design(design);
    out
}

impl<'a> SvPrinter<'a> {
    fn design(&mut self, design: &SvDesign) {
        self.out
            .push_str("// Generated by sylc. MVP SystemVerilog subset.\n\n");
        for (idx, module) in design.modules.iter().enumerate() {
            if idx > 0 {
                self.out.push('\n');
            }
            self.module(module);
        }
    }

    fn module(&mut self, module: &SvModule) {
        self.doc(0, module.doc.as_deref());
        self.out.push_str(&format!("module {}", module.name));
        if !module.params.is_empty() {
            self.out.push_str(" #(\n");
            for (idx, param) in module.params.iter().enumerate() {
                let comma = if idx + 1 == module.params.len() {
                    ""
                } else {
                    ","
                };
                self.param(param, comma);
            }
            self.out.push(')');
        }
        if module.ports.is_empty() {
            self.out.push_str(" ();\n");
        } else {
            self.out.push_str(" (\n");
            for (idx, port) in module.ports.iter().enumerate() {
                let comma = if idx + 1 == module.ports.len() {
                    ""
                } else {
                    ","
                };
                self.doc(4, port.doc.as_deref());
                self.out.push_str(&format!(
                    "    {} {}{}{}\n",
                    <&'static str>::from(port.direction),
                    range_prefix(&port.width),
                    port.name,
                    comma
                ));
            }
            self.out.push_str(");\n");
        }
        for item in &module.items {
            self.item(item, 2);
        }
        self.out.push_str("endmodule\n");
    }

    fn param(&mut self, param: &SvParam, comma: &str) {
        self.doc(4, param.doc.as_deref());
        self.out.push_str(&format!(
            "    parameter {} = {}{}\n",
            param.name, param.default, comma
        ));
    }

    fn doc(&mut self, indent: usize, doc: Option<&str>) {
        let Some(doc) = doc else {
            return;
        };
        let pad = " ".repeat(indent);
        for line in doc.lines() {
            if line.is_empty() {
                self.out.push_str(&format!("{pad}//\n"));
            } else {
                self.out.push_str(&format!("{pad}// {line}\n"));
            }
        }
    }

    fn item(&mut self, item: &SvItem, indent: usize) {
        let pad = " ".repeat(indent);
        match item {
            SvItem::LocalParam { name, value } => {
                self.out.push_str(&format!("{pad}localparam {name} = "));
                self.expr(value);
                self.out.push_str(";\n");
            }
            SvItem::Wire { width, name } => {
                self.out
                    .push_str(&format!("{pad}wire {}{};\n", range_prefix(width), name));
            }
            SvItem::Reg { width, name } => {
                self.out
                    .push_str(&format!("{pad}reg {}{};\n", range_prefix(width), name));
            }
            SvItem::Assign { lhs, rhs } => {
                self.out.push_str(&format!("{pad}assign "));
                self.expr(lhs);
                self.out.push_str(" = ");
                self.expr(rhs);
                self.out.push_str(";\n");
            }
            SvItem::AlwaysReg {
                clock,
                target,
                reset,
                next,
            } => {
                self.out.push_str(&format!("{pad}always @(posedge "));
                self.expr(clock);
                self.out.push_str(") begin\n");
                self.out.push_str(&format!("{pad}  "));
                if let Some(reset) = reset {
                    self.out.push_str("if (");
                    self.expr(&reset.condition);
                    self.out.push_str(") ");
                    self.expr(target);
                    self.out.push_str(" <= ");
                    self.expr(&reset.value);
                    self.out.push_str(&format!(";\n{pad}  else "));
                    self.expr(target);
                    self.out.push_str(" <= ");
                    self.expr(next);
                    self.out.push_str(";\n");
                } else {
                    self.expr(target);
                    self.out.push_str(" <= ");
                    self.expr(next);
                    self.out.push_str(";\n");
                }
                self.out.push_str(&format!("{pad}end\n"));
            }
            SvItem::AlwaysAssert {
                clock,
                trigger,
                message,
            } => {
                self.out.push_str(&format!("{pad}always @(posedge "));
                self.expr(clock);
                self.out.push_str(") begin\n");
                self.out.push_str(&format!("{pad}  if ("));
                self.expr(trigger);
                self.out.push_str(") $error(");
                self.expr(message);
                self.out.push_str(");\n");
                self.out.push_str(&format!("{pad}end\n"));
            }
            SvItem::Instance(instance) => self.instance(instance, indent),
            SvItem::GenerateIf {
                cond,
                label,
                then_items,
                else_items,
            } => {
                self.out.push_str(&format!("{pad}generate\n"));
                self.out.push_str(&format!("{pad}  if ("));
                self.expr(cond);
                self.out.push_str(&format!(") begin : {label}\n"));
                for item in then_items {
                    self.item(item, indent + 4);
                }
                if !else_items.is_empty() {
                    self.out
                        .push_str(&format!("{pad}  end else begin : {label}_else\n"));
                    for item in else_items {
                        self.item(item, indent + 4);
                    }
                }
                self.out
                    .push_str(&format!("{pad}  end\n{pad}endgenerate\n"));
            }
            SvItem::GenerateFor {
                genvar,
                start,
                end,
                label,
                items,
            } => {
                self.out.push_str(&format!("{pad}genvar {genvar};\n"));
                self.out.push_str(&format!("{pad}generate\n"));
                self.out.push_str(&format!("{pad}  for ({genvar} = "));
                self.expr(start);
                self.out.push_str(&format!("; {genvar} < "));
                self.expr(end);
                self.out
                    .push_str(&format!("; {genvar} = {genvar} + 1) begin : {label}\n"));
                for item in items {
                    self.item(item, indent + 4);
                }
                self.out
                    .push_str(&format!("{pad}  end\n{pad}endgenerate\n"));
            }
            SvItem::InitialError { message } => {
                self.out
                    .push_str(&format!("{pad}initial begin\n{pad}  $error("));
                self.expr(message);
                self.out.push_str(&format!(");\n{pad}end\n"));
            }
        }
    }

    fn expr(&mut self, expr: &SvExpr) {
        match expr {
            SvExpr::Ident(name) => self.out.push_str(name),
            SvExpr::Int(value) => self.out.push_str(&value.to_string()),
            SvExpr::Bool(value) => {
                if *value {
                    self.out.push_str("1'b1");
                } else {
                    self.out.push_str("1'b0");
                }
            }
            SvExpr::Str(value) => {
                self.out.push('"');
                self.out.push_str(value);
                self.out.push('"');
            }
            SvExpr::HighZ => self.out.push_str("'z"),
            SvExpr::Zero => self.out.push_str("'0"),
            SvExpr::Unary { op, expr } => {
                self.out.push('(');
                self.out.push_str(<&'static str>::from(*op));
                self.expr(expr);
                self.out.push(')');
            }
            SvExpr::Binary { op, left, right } => {
                self.out.push('(');
                self.expr(left);
                self.out.push(' ');
                self.out.push_str(<&'static str>::from(*op));
                self.out.push(' ');
                self.expr(right);
                self.out.push(')');
            }
            SvExpr::Mux {
                cond,
                then_value,
                else_value,
            } => {
                self.out.push('(');
                self.expr(cond);
                self.out.push_str(" ? ");
                self.expr(then_value);
                self.out.push_str(" : ");
                self.expr(else_value);
                self.out.push(')');
            }
            SvExpr::Select {
                mode,
                arms,
                default,
            } => {
                self.out.push_str("/* ");
                self.out.push_str(<&'static str>::from(*mode));
                self.out.push_str(" */ ");
                self.select_chain(arms, default);
            }
            SvExpr::Concat(parts) => {
                self.out.push('{');
                for (idx, part) in parts.iter().enumerate() {
                    if idx > 0 {
                        self.out.push_str(", ");
                    }
                    self.expr(part);
                }
                self.out.push('}');
            }
            SvExpr::Slice { value, high, low } => {
                self.expr(value);
                self.out.push_str(&format!("[{high}:{low}]"));
            }
            SvExpr::IndexedPartSelect {
                value,
                index,
                width,
            } => {
                self.expr(value);
                self.out.push('[');
                self.expr(index);
                self.out.push_str(&format!("*({width}) +: ({width})]"));
            }
            SvExpr::Index { value, index } => {
                self.expr(value);
                self.out.push('[');
                self.expr(index);
                self.out.push(']');
            }
            SvExpr::Call { name, args } => {
                self.out.push_str(name);
                self.out.push('(');
                for (idx, arg) in args.iter().enumerate() {
                    if idx > 0 {
                        self.out.push_str(", ");
                    }
                    self.expr(arg);
                }
                self.out.push(')');
            }
        }
    }

    fn select_chain(&mut self, arms: &[SvSelectArm], default: &SvExpr) {
        if let Some((arm, rest)) = arms.split_first() {
            self.out.push('(');
            self.expr(&arm.guard);
            self.out.push_str(" ? ");
            self.expr(&arm.value);
            self.out.push_str(" : ");
            self.select_chain(rest, default);
            self.out.push(')');
        } else {
            self.expr(default);
        }
    }

    fn instance(&mut self, instance: &SvInstance, indent: usize) {
        let pad = " ".repeat(indent);
        self.out.push_str(&format!("{pad}{}", instance.module));
        if !instance.params.is_empty() {
            let params = instance
                .params
                .iter()
                .map(|param| format!(".{}({})", param.name, param.value))
                .collect::<Vec<_>>()
                .join(", ");
            self.out.push_str(&format!(" #({params})"));
        }
        self.out.push_str(&format!(" {} (", instance.name));
        for (idx, connection) in instance.connections.iter().enumerate() {
            if idx > 0 {
                self.out.push_str(", ");
            }
            self.out.push_str(&format!(".{}(", connection.formal));
            self.expr(&connection.actual);
            self.out.push(')');
        }
        self.out.push_str(");\n");
    }
}

fn range_prefix(width: &str) -> String {
    if width == "1" {
        String::new()
    } else if let Ok(width) = width.parse::<u64>() {
        if width <= 1 {
            String::new()
        } else {
            format!("[{}:0] ", width - 1)
        }
    } else {
        format!("[({width})-1:0] ")
    }
}
